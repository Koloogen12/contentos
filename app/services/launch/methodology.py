"""Справочники методологии прогрева.

Первоисточник — шесть уроков по прогреву к запуску инфопродукта. Мы взяли
оттуда семь этапов, рубрики конструктора, восемнадцать психологических
триггеров и чек-лист смыслов, но НЕ переносили методологию дословно: в ней
есть противоречия и пробелы. Всё, что мы решали за автора, помечено
`OURS` — чтобы через полгода не выдать наш дефолт за цитату.

Три главных отличия от первоисточника:

1. Окно продаж. В уроках семь этапов упираются в дату открытия продаж, а
   длина окна не названа вообще. При этом в разобранном там же кейсе на
   75 млн после открытия добрали 25 млн — треть запуска. Поэтому ось у нас
   продолжается за открытие: этап 7 это окно продаж, а последний день
   получает свой набор рубрик.
2. Рубрика «Снятие возражений» (12) — наша. В окне продаж работать нечем:
   у автора там только «продажи в блоге», а возражения снимаются кейсами
   и разбором, и это отдельный смысл, а не продажа.
3. Сквозные триггеры. В первоисточнике семь триггеров из восемнадцати не
   привязаны ни к одному этапу и потому выпадают из любой проверки. Мы
   помечаем их `cross_stage`: они проверяются на всём прогреве, а не на
   этапе.
"""
